export function projectUk(lat: number, lon: number): [x: number, y: number] {
  const lat0 = 54.5;
  const lon0 = -3.0;
  const x = (lon - lon0) * Math.cos((lat0 * Math.PI) / 180);
  const y = lat - lat0;
  // Normalise roughly into [-1, 1] given the UK's extent.
  return [x / 5.2, y / 5.2];
}
